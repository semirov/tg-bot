/** Максимальная длина «окончания» после основы. */
const MAX_ENDING_LENGTH = 3;

/** Нормализует текст для сравнения: нижний регистр, ё → е. */
function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е');
}

/**
 * Возвращает true, если сообщение похоже на обращение к боту по слову/мату.
 * Работает по словам (не подстроками), чтобы не ловить случайные совпадения.
 */
export function isAddressedToBot(content: string | null | undefined): boolean {
  if (!content) {
    return false;
  }

  const words = normalize(content).split(/[^0-9a-zа-я]+/);

  for (const word of words) {
    if (!word) {
      continue;
    }
    if (TROLL_ADDRESS_WORDS.has(word)) {
      return true;
    }
    for (const stem of TROLL_ADDRESS_STEMS) {
      const extra = word.length - stem.length;
      if (extra >= 0 && extra <= MAX_ENDING_LENGTH && word.startsWith(stem)) {
        return true;
      }
    }
  }

  return false;
}

/** Фразы, которыми спрашивают, что бот умеет. */
const CAPABILITY_PATTERNS: readonly RegExp[] = [
  /что\s+ты\s+умеешь/,
  /что\s+умеешь/,
  /что\s+ты\s+можешь/,
  /какие\s+(?:у\s+тебя\s+)?команды/,
  /список\s+команд/,
  /как\s+(?:тобой|тебя)\s+(?:пользоваться|использовать)/,
  /\bhelp\b/,
  /хелп/,
];

/**
 * Возвращает true, если сообщение — вопрос «что ты умеешь / какие команды».
 * Сравнение идёт по нормализованному тексту (нижний регистр, ё → е).
 */
export function isCapabilityQuestion(content: string | null | undefined): boolean {
  if (!content) {
    return false;
  }
  const normalized = normalize(content);
  return CAPABILITY_PATTERNS.some((pattern) => pattern.test(normalized));
}
