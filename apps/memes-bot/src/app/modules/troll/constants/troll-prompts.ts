/**
 * Дописывается к заданию при повторной попытке: что именно было не так
 * в забракованном ответе.
 */
export function buildRetryNote(previous: string, issues: string[], attempt: number): string {
  const problems = issues.length ? issues.join('; ') : 'ответ вышел слабым';
  return `\n\nПОПЫТКА ${attempt}. Предыдущий ответ забракован по ревизии: ${problems}\nПредыдущий вариант: «${previous}»\nПерепиши ответ своими словами: исправь именно эти проблемы и не повторяй старую формулировку.`;
}

